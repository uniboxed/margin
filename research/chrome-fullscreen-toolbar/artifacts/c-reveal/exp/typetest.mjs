import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const require = createRequire('/home/user/margin/package.json');
const { chromium } = require('playwright');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const xdo = (...a) => { try { return execFileSync('xdotool', a, { encoding: 'utf8' }).trim(); } catch (e) { return 'ERR ' + e.message.split('\n')[0]; } };
const ctx = await chromium.launchPersistentContext(mkdtempSync(join(tmpdir(), 'crv-')), { headless: false, viewport: null, args: ['--window-size=900,600', '--window-position=0,0'] });
const page = ctx.pages()[0];
await page.setContent('<title>typetest</title><body><input id=i></body>');
await page.evaluate(() => { window.__keys = []; addEventListener('keydown', (e) => __keys.push(e.key), true); });
await sleep(500);
const wid = xdo('search', '--onlyvisible', '--name', 'typetest').split('\n').pop();
console.log('wid', wid, 'focus before', xdo('getwindowfocus', 'getwindowname'));
xdo('windowfocus', '--sync', wid);
console.log('focus after windowfocus', xdo('getwindowfocus', 'getwindowname'));
xdo('mousemove', '--window', wid, '400', '300'); xdo('click', '1');
await sleep(300);
xdo('type', '--delay', '40', 'ab');
await sleep(400);
console.log('XTEST type:', await page.evaluate(() => ({ keys: __keys.join(''), hasFocus: document.hasFocus() })));
xdo('type', '--window', wid, '--delay', '40', 'cd');
await sleep(400);
console.log('XSendEvent type:', await page.evaluate(() => ({ keys: __keys.join(''), hasFocus: document.hasFocus() })));
await ctx.close();
