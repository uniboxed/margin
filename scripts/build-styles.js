// Bundles content/*.css into content/styles.js so content scripts can apply
// styles synchronously (fetching them delays the sidebar until the page's own
// loads finish in Safari). Run `npm run styles` after editing the CSS; a unit
// test fails if styles.js is out of date.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { pageCardCss } from './page-card.js';

const root = new URL('../extension/content/', import.meta.url);

export function buildStyles() {
  const css = (name) => readFileSync(new URL(`${name}.css`, root), 'utf8');
  return `// Generated by scripts/build-styles.js from content/sidebar.css and
// content/palette.css. Do not edit; run \`npm run styles\`.
(() => {
  const Margin = (globalThis.Margin ??= {});
  Margin.styles = {
    sidebar: ${JSON.stringify(css('sidebar'))},
    palette: ${JSON.stringify(css('palette'))},
  };
})();
`;
}

// The page card's corners and shadow (scripts/page-card.js) are written into
// the CSS that draws the card, between these markers:
//   /* page-card: generated … */ … /* /page-card */
// "page-card!" adds !important (the placeholder must beat page styles).
export const PAGE_CARD_FILES = ['content/sidebar.css', 'content/docked.template.css', 'newtab/newtab.css'];
const PAGE_CARD_BLOCK = /^([ \t]*)\/\* (page-card!?): generated[^*]*\*\/\n[\s\S]*?^[ \t]*\/\* \/page-card \*\/$/gm;
export function withPageCard(css) {
  return css.replace(PAGE_CARD_BLOCK, (_, indent, kind) =>
    `${indent}/* ${kind}: generated by scripts/build-styles.js from scripts/page-card.js; run \`npm run styles\` */\n` +
    `${pageCardCss({ important: kind === 'page-card!', indent })}\n${indent}/* /page-card */`);
}

// First-paint placeholders, one per sidebar width (keep in sync with
// shared/view.js WIDTH: 160–500 in 10px steps).
export const DOCKED_WIDTHS = Array.from({ length: (500 - 160) / 10 + 1 }, (_, i) => 160 + i * 10);
export function buildDocked(width) {
  const header = `/* Generated by scripts/build-styles.js from content/docked.template.css\n   for a ${width}px sidebar. Do not edit; run \`npm run styles\`. */\n`;
  const template = readFileSync(new URL('docked.template.css', root), 'utf8');
  // Only the rules: the template's comment mentions the placeholder too.
  return header + template.slice(template.indexOf('*/') + 3).replaceAll('{{WIDTH}}', String(width));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const extension = new URL('../', root);
  for (const f of PAGE_CARD_FILES) {
    const file = new URL(f, extension);
    const css = readFileSync(file, 'utf8');
    if (!PAGE_CARD_BLOCK.test(css)) throw new Error(`${f}: no page-card block`);
    PAGE_CARD_BLOCK.lastIndex = 0;
    writeFileSync(file, withPageCard(css));
  }
  writeFileSync(new URL('styles.js', root), buildStyles());
  const dir = new URL('docked/', root);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir);
  for (const w of DOCKED_WIDTHS) writeFileSync(new URL(`w-${w}.css`, dir), buildDocked(w));
  console.log(`styles.js + ${readdirSync(dir).length} docked placeholders`);
}
