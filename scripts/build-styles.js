// Bundles content/*.css into content/styles.js so content scripts can apply
// styles synchronously (fetching them delays the sidebar until the page's own
// loads finish in Safari). Run `npm run styles` after editing the CSS; a unit
// test fails if styles.js is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../extension/content/', import.meta.url);

export function buildStyles() {
  const css = (name) => readFileSync(new URL(`${name}.css`, root), 'utf8');
  return `// Generated by scripts/build-styles.js from content/sidebar.css and
// content/palette.css. Do not edit; run \`npm run styles\`.
(() => {
  const Margin = (globalThis.Margin ??= {});
  Margin.styles = {
    sidebar: ${JSON.stringify(css('sidebar'))},
    palette: ${JSON.stringify(css('palette'))},
  };
})();
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('styles.js', root), buildStyles());
}
