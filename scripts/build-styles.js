// Generated theme files, committed like the rest of extension/:
//  - themes/<id>/assets.js: the theme's CSS (styles/*.css) and new-tab markup
//    (newtab.html) as strings, so its scripts apply them synchronously
//    (fetching them delays the sidebar until the page's own loads finish in
//    Safari);
//  - themes/<id>/docked/w-<width>.css: first-paint placeholders, one per
//    sidebar width, from the theme's docked.template.css, and closed.css, the
//    frame alone. Their box is shared/page-box.js's, as in the page.
// Run `npm run styles` after editing a theme's CSS, markup or template; a
// unit test fails if a generated file is out of date.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { THEMES } from '../extension/themes/index.js';
import { WIDTH } from '../extension/themes/arcadia/theme.js';
import { boxRules } from '../extension/shared/page-box.js';

const root = new URL('../extension/', import.meta.url);
const themeDir = (id) => new URL(`themes/${id}/`, root);
const camel = (name) => name.replace(/-(.)/g, (_, c) => c.toUpperCase());

export function buildAssets(id) {
  const dir = themeDir(id);
  const css = readdirSync(new URL('styles/', dir)).filter((f) => f.endsWith('.css')).sort();
  const lines = css.map((f) => `export const ${camel(f.slice(0, -4))}Css = ${JSON.stringify(readFileSync(new URL(`styles/${f}`, dir), 'utf8'))};`);
  const html = new URL('newtab.html', dir);
  if (existsSync(html)) {
    // Without the file's own leading comment.
    const markup = readFileSync(html, 'utf8').replace(/^<!--[\s\S]*?-->\n/, '');
    lines.push(`export const newtabHtml = ${JSON.stringify(markup)};`);
  }
  return `// Generated by scripts/build-styles.js from themes/${id}/styles/*.css and
// newtab.html. Do not edit; run \`npm run styles\`.
${lines.join('\n')}
`;
}

// Arcadia's placeholders: one per sidebar width it allows (theme.js WIDTH).
export const DOCKED_WIDTHS = Array.from({ length: (WIDTH.max - WIDTH.min) / WIDTH.step + 1 }, (_, i) => WIDTH.min + i * WIDTH.step);
const docked = { arcadia: DOCKED_WIDTHS };
export const dockedWidths = (id) => docked[id] ?? [];
const FRAME = 8; // the frame's width (theme geometry.inset)
// Not on a page an old copy laid out, which stays as it is until it reloads.
const PLACED = 'html:not([data-margin-docked="off"], [data-margin-shell], [data-margin-frameless])';
const box = (left) => boxRules(PLACED, { left, top: FRAME, right: FRAME, bottom: FRAME });

export function buildDocked(id, width) {
  const header = `/* Generated by scripts/build-styles.js from themes/${id}/docked.template.css\n   for a ${width}px sidebar. Do not edit; run \`npm run styles\`. */\n`;
  const template = readFileSync(new URL('docked.template.css', themeDir(id)), 'utf8');
  // Only the rules: the template's comment mentions the placeholder too.
  return header + template.slice(template.indexOf('*/') + 3).replaceAll('{{BOX}}', box(width)).replaceAll('{{WIDTH}}', String(width));
}

export function buildClosed(id) {
  return readFileSync(new URL('closed.template.css', themeDir(id)), 'utf8').replaceAll('{{BOX}}', box(FRAME));
}

function writeDir(dir, files) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [name, text] of files) writeFileSync(new URL(name, dir), text);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  let count = 0;
  for (const { id } of Object.values(THEMES)) {
    writeFileSync(new URL('assets.js', themeDir(id)), buildAssets(id));
    const widths = dockedWidths(id);
    const files = widths.map((w) => [`w-${w}.css`, buildDocked(id, w)]);
    if (existsSync(new URL('closed.template.css', themeDir(id)))) files.push(['closed.css', buildClosed(id)]);
    if (files.length) writeDir(new URL('docked/', themeDir(id)), files);
    count += files.length;
  }
  console.log(`themes: ${Object.keys(THEMES).join(', ')}; ${count} placeholders`);
}
